/**
 * Jurisdictions with encoded requirement data. Placeholder until /ontology
 * lands — replace this constant with coverage read from the ontology loader
 * rather than extending the literal.
 */
export const ENCODED_JURISDICTIONS = ["CA", "TX"];

export function jurisdictionName(code: string): string {
  return JURISDICTIONS.find((j) => j.code === code)?.name ?? code;
}

export function isEncoded(code: string): boolean {
  return ENCODED_JURISDICTIONS.includes(code);
}

export function directionOf(sending: string, receiving: string): string {
  return `${sending}_to_${receiving}`;
}
